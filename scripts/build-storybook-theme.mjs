// Storybook's manager (the docs site at volter-ai.github.io/widget-shell) in the Volter brand
// (company decision 0028). Storybook's theme takes plain colour strings, not CSS variables, so the
// brand's light roles are resolved here at build into .storybook/brand-theme.generated.ts (gitignored).
// A failed fetch fails the build.
import { mkdirSync, writeFileSync } from "node:fs";
import { brandResolver } from "./brand-roles.mjs";

const { tokens } = await brandResolver("storybook theme");
const s = tokens.semantic;
const theme = {
  base: "light",
  brandTitle: "Widget Shell",
  brandUrl: "https://github.com/volter-ai/widget-shell",
  brandImage: "https://brand.volter.ai/logo/widget-shell/svg?size=64",
  brandTarget: "_self",
  colorPrimary: s.action.default,
  colorSecondary: s.action.default,
  appBg: s.surface.page,
  appContentBg: s.surface.raised,
  appPreviewBg: s.surface.raised,
  appHoverBg: s.selection.soft,
  appBorderColor: s.border.default,
  appBorderRadius: 4,
  fontBase: tokens.font.ui,
  fontCode: tokens.font.data,
  textColor: s.text.primary,
  textInverseColor: s.text.onStrong,
  textMutedColor: s.text.muted,
  barTextColor: s.text.muted,
  barHoverColor: s.text.primary,
  barSelectedColor: s.text.primary,
  barBg: s.surface.raised,
  buttonBg: s.surface.raised,
  buttonBorder: s.border.strong,
  inputBg: s.surface.raised,
  inputBorder: s.border.default,
  inputTextColor: s.text.primary,
  inputBorderRadius: 3,
};
writeFileSync(
  new URL("../.storybook/brand-theme.generated.ts", import.meta.url),
  `// Generated by scripts/build-storybook-theme.mjs from https://brand.volter.ai/tokens.json; do not edit.\nexport const brandTheme = ${JSON.stringify(theme, null, 2)} as const;\n`,
);
// The manager's frame loads the brand's own stylesheet and faces, served from the Storybook's static
// folder (public/brand, gitignored) and linked by .storybook/main.ts's managerHead.
const BRAND = "https://brand.volter.ai";
const fetched = async (path) => {
  const r = await fetch(`${BRAND}${path}`, { signal: AbortSignal.timeout(20_000) });
  if (!r.ok) {
    console.error(`storybook theme: ${path}: HTTP ${r.status}`);
    process.exit(1);
  }
  return Buffer.from(await r.arrayBuffer());
};
const css = (await fetched("/tokens.css")).toString("utf8").replaceAll(`${BRAND}/fonts/`, "fonts/");
const out = new URL("../public/brand/", import.meta.url);
mkdirSync(new URL("fonts/", out), { recursive: true });
for (const face of new Set([...css.matchAll(/fonts\/([A-Za-z0-9_.-]+\.woff2)/g)].map((m) => m[1])))
  writeFileSync(new URL(`fonts/${face}`, out), await fetched(`/fonts/${face}`));
writeFileSync(new URL("fonts/LICENSES.txt", out), await fetched("/fonts/LICENSES.txt"));
writeFileSync(new URL("tokens.css", out), css);
console.error("storybook theme: .storybook/brand-theme.generated.ts, public/brand/");
